# -*- coding: utf-8 -*-
"""
how_many_exports.py — сколько .odb надо перевыгрузить, чтобы сверка с аналитикой
что-то доказывала.

Вопрос руководителя (08.09.2026): «сколько именно выгрузок нужно? По всем расчётам
или достаточно какого-то подмножества?»

Ответ считается по уже извлечённым данным, а не по интуиции. Напряжение волочения
sigma_d = F/A восстановлено из 158 незавершённых расчётов (E-24): пока проволока в
волоке, протянутая часть под тянущей нагрузкой, и F/A постоянно вдоль прутка.
Пригодных после фильтров (sigma_d > 20 МПа, разброс вдоль прутка < 8 %) — 95.

Что из них следует:
  * разброс МКЭ вокруг верхнеграничного решения Авитцура при sigma_f = 320 МПа
    (измерено в конусе, VALIDATION.md §2) — СКО 18.4 МПа;
  * шаг sigma_d между соседними уровнями полуугла alpha по Авитцуру — в среднем
    11.4 МПа;
  * значит, чтобы различать уровни alpha, нужно SE среднего в уровне заметно меньше
    11.4 МПа, то есть 18.4/sqrt(n/5) МПа при n выгрузках на пять уровней.

Имеющиеся 95 расчётов покрывают только alpha = 12 и 16 градусов и только v = 10 м/мин,
поэтому зависимость от полуугла и от скорости по ним не проверяется вовсе.

Запуск:  python publication/reexport/how_many_exports.py
"""
import numpy as np

SIGMA_RESID = 18.4   # СКО (МКЭ − Авитцур) по 95 расчётам, МПа
STEP_ALPHA = 11.4    # средний шаг sigma_d между соседними уровнями alpha, МПа
N_LEVELS = 5         # alpha = 4, 8, 12, 16, 20 градусов


def resolution(n_runs: int) -> tuple:
    """SE среднего внутри уровня alpha и отношение шага к этому SE."""
    per_level = n_runs / N_LEVELS
    se = SIGMA_RESID / np.sqrt(per_level)
    return per_level, se, STEP_ALPHA / se


if __name__ == "__main__":
    print("выгрузок  на уровень  SE уровня, МПа   шаг/SE")
    for n in (30, 60, 93, 150, 300, 2443):
        per, se, ratio = resolution(n)
        print(f"  {n:5d}     {per:6.0f}         {se:6.1f}        {ratio:5.1f}")
    print()
    print("30  — хватает на общий MAPE (±1.4 п.п. по бутстрэпу), но не на зависимость от alpha")
    print("93  — reexport_list_extended.csv: 3 расчёта на каждую из 30 ячеек (Q, alpha)")
    print("150 — заметно лучше, дальше отдача падает")
    print("2443 — не нужно: 13.7 sigma вместо 2.7 при 26-кратном росте объёма работы")
